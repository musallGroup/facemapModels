"""
visualize_frontview_predictions.py

Creates an overlay QC video from:

1. The original Cam0 video
2. The HDF5 predictions generated by predict_frontview_v1.py

The output video is saved in:

FM_Front_View/2_Photon/Model_QC

Expected HDF5 structure:

frame_index
Facemap/
    nose_tip/
        x
        y
        likelihood
    ...
"""

from __future__ import annotations

from pathlib import Path
from tkinter import Tk, filedialog

import cv2
import h5py
import numpy as np


# ============================================================
# SETTINGS
# ============================================================

OUTPUT_DIR = Path(
    r"\\NASKAMPA\lts\Team\Mick\FM_Front_View"
    r"\2_Photon\Model_QC"
)

KEYPOINT_NAMES = [
    "nose_tip",
    "nose_bottom",
    "mouth",
    "lowerlip",
    "whiskerpad_left",
    "whiskerpad_right",
]

# Points below this likelihood are still shown,
# but marked with a small cross.
LIKELIHOOD_THRESHOLD = 0.80

POINT_RADIUS = 6
LINE_THICKNESS = 2
FONT_SCALE = 0.55

# None means: use every prediction contained in the H5 file.
MAX_OUTPUT_FRAMES: int | None = None

# Set to None to use the source video FPS.
OUTPUT_FPS: float | None = None


# ============================================================
# FILE SELECTION
# ============================================================

def select_file(
    title: str,
    filetypes: list[tuple[str, str]],
) -> Path:
    """Open a Windows file dialog."""

    root = Tk()
    root.withdraw()
    root.attributes("-topmost", True)

    selected = filedialog.askopenfilename(
        title=title,
        filetypes=filetypes,
    )

    root.destroy()

    if not selected:
        raise RuntimeError(f"No file selected for: {title}")

    path = Path(selected)

    if not path.exists():
        raise FileNotFoundError(
            f"Selected file does not exist:\n{path}"
        )

    return path


def select_video() -> Path:
    """Select the original Cam0 video."""

    return select_file(
        title="Select the original Cam0 video",
        filetypes=[
            ("Video files", "*.avi *.mp4 *.mov *.mkv"),
            ("AVI files", "*.avi"),
            ("All files", "*.*"),
        ],
    )


def select_prediction_file() -> Path:
    """Select the corresponding prediction HDF5 file."""

    return select_file(
        title="Select the Frontview prediction H5 file",
        filetypes=[
            ("HDF5 files", "*.h5 *.hdf5"),
            ("All files", "*.*"),
        ],
    )


# ============================================================
# LOAD PREDICTIONS
# ============================================================

def load_predictions(
    h5_path: Path,
) -> tuple[np.ndarray, dict[str, np.ndarray]]:
    """
    Load frame indices and predictions.

    Returns
    -------
    frame_indices:
        Shape (n_frames,)

    predictions:
        Dictionary where each keypoint contains an array
        with shape (n_frames, 3):

        x, y, likelihood
    """

    predictions: dict[str, np.ndarray] = {}

    with h5py.File(h5_path, "r") as h5_file:
        if "frame_index" not in h5_file:
            raise KeyError(
                "The H5 file does not contain 'frame_index'."
            )

        if "Facemap" not in h5_file:
            raise KeyError(
                "The H5 file does not contain the 'Facemap' group."
            )

        frame_indices = np.asarray(
            h5_file["frame_index"],
            dtype=np.int64,
        )

        facemap_group = h5_file["Facemap"]

        for keypoint_name in KEYPOINT_NAMES:
            if keypoint_name not in facemap_group:
                raise KeyError(
                    f"Keypoint missing in H5 file: {keypoint_name}"
                )

            keypoint_group = facemap_group[keypoint_name]

            for dataset_name in ["x", "y", "likelihood"]:
                if dataset_name not in keypoint_group:
                    raise KeyError(
                        f"Missing dataset: "
                        f"Facemap/{keypoint_name}/{dataset_name}"
                    )

            x = np.asarray(
                keypoint_group["x"],
                dtype=np.float32,
            )

            y = np.asarray(
                keypoint_group["y"],
                dtype=np.float32,
            )

            likelihood = np.asarray(
                keypoint_group["likelihood"],
                dtype=np.float32,
            )

            predictions[keypoint_name] = np.column_stack(
                [x, y, likelihood]
            )

    expected_length = len(frame_indices)

    for keypoint_name, values in predictions.items():
        if len(values) != expected_length:
            raise RuntimeError(
                f"Length mismatch for {keypoint_name}: "
                f"{len(values)} predictions versus "
                f"{expected_length} frame indices."
            )

    return frame_indices, predictions


# ============================================================
# DRAWING
# ============================================================

def create_colors(
    number_of_keypoints: int,
) -> list[tuple[int, int, int]]:
    """
    Create visually distinct OpenCV BGR colors.
    """

    hsv_values = np.linspace(
        0,
        179,
        number_of_keypoints,
        endpoint=False,
        dtype=np.uint8,
    )

    colors: list[tuple[int, int, int]] = []

    for hue in hsv_values:
        hsv_pixel = np.uint8([[[hue, 220, 255]]])
        bgr_pixel = cv2.cvtColor(
            hsv_pixel,
            cv2.COLOR_HSV2BGR,
        )[0, 0]

        colors.append(
            tuple(int(value) for value in bgr_pixel)
        )

    return colors


def draw_cross(
    frame: np.ndarray,
    x: int,
    y: int,
    color: tuple[int, int, int],
) -> None:
    """Draw a cross for low-likelihood predictions."""

    size = POINT_RADIUS + 2

    cv2.line(
        frame,
        (x - size, y - size),
        (x + size, y + size),
        color,
        LINE_THICKNESS,
        cv2.LINE_AA,
    )

    cv2.line(
        frame,
        (x - size, y + size),
        (x + size, y - size),
        color,
        LINE_THICKNESS,
        cv2.LINE_AA,
    )


def draw_prediction_overlay(
    frame: np.ndarray,
    prediction_index: int,
    source_frame_index: int,
    predictions: dict[str, np.ndarray],
    colors: list[tuple[int, int, int]],
) -> np.ndarray:
    """Draw all six keypoints onto one video frame."""

    overlay = frame.copy()

    frame_height, frame_width = overlay.shape[:2]

    for keypoint_index, keypoint_name in enumerate(
        KEYPOINT_NAMES
    ):
        x_float, y_float, likelihood = predictions[
            keypoint_name
        ][prediction_index]

        if not (
            np.isfinite(x_float)
            and np.isfinite(y_float)
            and np.isfinite(likelihood)
        ):
            continue

        x = int(round(float(x_float)))
        y = int(round(float(y_float)))

        if not (
            0 <= x < frame_width
            and 0 <= y < frame_height
        ):
            continue

        color = colors[keypoint_index]

        if likelihood >= LIKELIHOOD_THRESHOLD:
            cv2.circle(
                overlay,
                (x, y),
                POINT_RADIUS,
                color,
                thickness=-1,
                lineType=cv2.LINE_AA,
            )

            cv2.circle(
                overlay,
                (x, y),
                POINT_RADIUS + 2,
                (255, 255, 255),
                thickness=1,
                lineType=cv2.LINE_AA,
            )
        else:
            draw_cross(
                frame=overlay,
                x=x,
                y=y,
                color=color,
            )

        label = f"{keypoint_name} {likelihood:.2f}"

        text_x = min(
            x + 9,
            max(0, frame_width - 200),
        )

        text_y = max(
            20,
            y - 8,
        )

        cv2.putText(
            overlay,
            label,
            (text_x, text_y),
            cv2.FONT_HERSHEY_SIMPLEX,
            FONT_SCALE,
            (0, 0, 0),
            thickness=3,
            lineType=cv2.LINE_AA,
        )

        cv2.putText(
            overlay,
            label,
            (text_x, text_y),
            cv2.FONT_HERSHEY_SIMPLEX,
            FONT_SCALE,
            color,
            thickness=1,
            lineType=cv2.LINE_AA,
        )

    header = (
        f"Source frame: {source_frame_index}   "
        f"Likelihood threshold: {LIKELIHOOD_THRESHOLD:.2f}"
    )

    cv2.putText(
        overlay,
        header,
        (20, 35),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.75,
        (0, 0, 0),
        thickness=4,
        lineType=cv2.LINE_AA,
    )

    cv2.putText(
        overlay,
        header,
        (20, 35),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.75,
        (255, 255, 255),
        thickness=2,
        lineType=cv2.LINE_AA,
    )

    return overlay


# ============================================================
# VIDEO CREATION
# ============================================================

def create_qc_video(
    video_path: Path,
    h5_path: Path,
    frame_indices: np.ndarray,
    predictions: dict[str, np.ndarray],
) -> Path:
    """Create the overlay QC video."""

    capture = cv2.VideoCapture(str(video_path))

    if not capture.isOpened():
        raise RuntimeError(
            f"Could not open video:\n{video_path}"
        )

    source_fps = capture.get(cv2.CAP_PROP_FPS)
    frame_width = int(
        capture.get(cv2.CAP_PROP_FRAME_WIDTH)
    )
    frame_height = int(
        capture.get(cv2.CAP_PROP_FRAME_HEIGHT)
    )
    total_source_frames = int(
        capture.get(cv2.CAP_PROP_FRAME_COUNT)
    )

    if source_fps <= 0:
        source_fps = 30.0

    output_fps = (
        source_fps
        if OUTPUT_FPS is None
        else float(OUTPUT_FPS)
    )

    number_of_output_frames = len(frame_indices)

    if MAX_OUTPUT_FRAMES is not None:
        number_of_output_frames = min(
            number_of_output_frames,
            int(MAX_OUTPUT_FRAMES),
        )

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    output_path = OUTPUT_DIR / (
        f"{video_path.stem}_Frontview_v1_6kp_QC.mp4"
    )

    fourcc = cv2.VideoWriter_fourcc(*"mp4v")

    writer = cv2.VideoWriter(
        str(output_path),
        fourcc,
        output_fps,
        (frame_width, frame_height),
    )

    if not writer.isOpened():
        capture.release()

        raise RuntimeError(
            f"Could not create output video:\n{output_path}"
        )

    colors = create_colors(
        len(KEYPOINT_NAMES)
    )

    print("\n========================================")
    print("VIDEO SETTINGS")
    print("========================================")
    print(f"Source video:        {video_path}")
    print(f"Prediction file:     {h5_path}")
    print(f"Source dimensions:   {frame_width} x {frame_height}")
    print(f"Source FPS:          {source_fps:.3f}")
    print(f"Output FPS:          {output_fps:.3f}")
    print(f"Source frame count:  {total_source_frames}")
    print(f"Overlay frames:      {number_of_output_frames}")

    print("\n========================================")
    print("CREATING QC VIDEO")
    print("========================================")

    try:
        for prediction_index in range(
            number_of_output_frames
        ):
            source_frame_index = int(
                frame_indices[prediction_index]
            )

            capture.set(
                cv2.CAP_PROP_POS_FRAMES,
                source_frame_index,
            )

            success, frame = capture.read()

            if not success:
                raise RuntimeError(
                    f"Could not read source frame "
                    f"{source_frame_index}."
                )

            overlay = draw_prediction_overlay(
                frame=frame,
                prediction_index=prediction_index,
                source_frame_index=source_frame_index,
                predictions=predictions,
                colors=colors,
            )

            writer.write(overlay)

            if (
                prediction_index == 0
                or (prediction_index + 1) % 50 == 0
                or prediction_index + 1
                == number_of_output_frames
            ):
                print(
                    f"Processed "
                    f"{prediction_index + 1}/"
                    f"{number_of_output_frames} frames"
                )

    finally:
        capture.release()
        writer.release()

    return output_path


# ============================================================
# MAIN
# ============================================================

def main() -> None:
    """Run the complete overlay pipeline."""

    print("\n========================================")
    print("FRONTVIEW PREDICTION VISUALIZATION")
    print("========================================")

    print("\nSelect the original Cam0 video.")
    video_path = select_video()

    print("\nSelect the corresponding prediction H5 file.")
    h5_path = select_prediction_file()

    print("\nSelected video:")
    print(video_path)

    print("\nSelected prediction file:")
    print(h5_path)

    print("\n========================================")
    print("LOADING PREDICTIONS")
    print("========================================")

    frame_indices, predictions = load_predictions(
        h5_path
    )

    print(f"Prediction frames: {len(frame_indices)}")
    print(f"Keypoints:        {len(predictions)}")

    output_path = create_qc_video(
        video_path=video_path,
        h5_path=h5_path,
        frame_indices=frame_indices,
        predictions=predictions,
    )

    print("\n========================================")
    print("QC VIDEO COMPLETE")
    print("========================================")
    print("\nSaved to:")
    print(output_path)


if __name__ == "__main__":
    main()